'''
DESAFIO 04
> (Maior que)
< (Menor que)
>= (Maior ou igual a)
<= (Menor ou igual a)
== (Igual a — atenção: usamos dois sinais de igual para comparar, pois um sinal sozinho = serve para guardar valor em variável!)
!= (Diferente de)
'''
print(5>3)#True
print(5<3)#False
print(5>=3)#True
print(5<=3)#False
print(5==3)#False
print(5!=3)#True